/** Languages with more plural categories (Russian: one/few/many/other) may add `_few` / `_many`. */
type PluralExtras<T> = {
  [K in keyof T as K extends `${infer Base}_one` ? `${Base}_few` | `${Base}_many` : never]?: string;
};
type Shape<T> = { [K in keyof T]: T[K] extends string ? string : Shape<T[K]> } & PluralExtras<T>;
/** Every translation must provide exactly the keys of the English catalog. */
export type Catalog = Shape<typeof en>;
